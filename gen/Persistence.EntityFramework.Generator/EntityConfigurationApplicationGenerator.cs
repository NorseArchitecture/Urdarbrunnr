using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using Norse.Abstractions.Emit;

namespace Norse.Persistence.EntityFramework.Generator;

[Generator]
public sealed class EntityConfigurationApplicationGenerator : IIncrementalGenerator
{
	const string NorseEntityNamespace = "Norse.Persistence.EntityFramework";
	const string NorseEntityInterfaceMetadataName = "INorseEntity`1";
	const string NorseDbContextMetadataName = "Norse.Persistence.EntityFramework.NorseDbContext";

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		var entityDeclarations = context.SyntaxProvider.CreateSyntaxProvider(
			static (node, _) => node is TypeDeclarationSyntax { TypeParameterList: null } typeDeclaration &&
				(typeDeclaration.IsKind(SyntaxKind.ClassDeclaration) || typeDeclaration.IsKind(SyntaxKind.RecordDeclaration)),
			static (ctx, _) => (TypeDeclarationSyntax)ctx.Node);

		var compilationAndDeclarations = context.CompilationProvider.Combine(entityDeclarations.Collect());

		context.RegisterSourceOutput(compilationAndDeclarations, static (ctx, source) =>
		{
			var (compilation, typeDeclarations) = source;
			var entities = FindEntities(compilation, typeDeclarations);
			var tier1Context = FindPartialTier1Context(compilation, typeDeclarations);

			if (entities.Count == 0 && tier1Context is null)
				return;

			var text = BuildSource(entities, tier1Context);
			ctx.AddSource("NorseEntityConfigurationExtensions.g.cs", SourceText.From(text, Utf8NoBom.Encoding));
		});
	}

	static IList<string> FindEntities(Compilation compilation, IList<TypeDeclarationSyntax> typeDeclarations)
	{
		IList<string> results = [];

		foreach (var typeDeclaration in typeDeclarations)
		{
			var model = compilation.GetSemanticModel(typeDeclaration.SyntaxTree);
			if (model.GetDeclaredSymbol(typeDeclaration) is not INamedTypeSymbol type)
				continue;

			if (type.IsAbstract)
				continue;

			var implementsSelf = type.AllInterfaces.Any(i =>
				i.OriginalDefinition.MetadataName == NorseEntityInterfaceMetadataName &&
				i.OriginalDefinition.ContainingNamespace?.ToDisplayString() == NorseEntityNamespace &&
				i.TypeArguments.Length == 1 &&
				SymbolEqualityComparer.Default.Equals(i.TypeArguments[0], type));

			if (implementsSelf)
				results.Add(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
		}

		return results;
	}

	static INamedTypeSymbol? FindPartialTier1Context(Compilation compilation, IList<TypeDeclarationSyntax> typeDeclarations)
	{
		foreach (var typeDeclaration in typeDeclarations)
		{
			if (!typeDeclaration.Modifiers.Any(SyntaxKind.PartialKeyword))
				continue;

			var model = compilation.GetSemanticModel(typeDeclaration.SyntaxTree);
			if (model.GetDeclaredSymbol(typeDeclaration) is not INamedTypeSymbol type)
				continue;

			if (InheritsNorseDbContext(type))
				return type;
		}

		return null;
	}

	static bool InheritsNorseDbContext(INamedTypeSymbol type)
	{
		for (var current = type.BaseType; current is not null; current = current.BaseType)
			if (current.ToDisplayString() == NorseDbContextMetadataName)
				return true;

		return false;
	}

	static string BuildSource(IList<string> entities, INamedTypeSymbol? tier1Context)
	{
		StringBuilder sb = new();

		sb.AppendCSharp("""
			// <auto-generated />
			#nullable enable
			using Microsoft.EntityFrameworkCore;

			internal static class GeneratedNorseModelConfigurations
			{
				public static ModelBuilder ApplyNorseConfigurations(this ModelBuilder builder)
				{
			""");

		foreach (var entity in entities)
			sb.AppendCSharp($"""
						builder.Entity<{entity}>(eb => {entity}.Configure(eb));
				""");

		sb.AppendCSharp("""
					return builder;
				}
			}
			""");

		if (tier1Context is not null)
		{
			var ns = tier1Context.ContainingNamespace;
			var name = tier1Context.Name;

			if (ns.IsGlobalNamespace)
				sb.AppendCSharp($$"""

					partial class {{name}}
					{
						protected override void ConfigureNorseEntities(ModelBuilder builder)
						{
							base.ConfigureNorseEntities(builder);
							builder.ApplyNorseConfigurations();
						}
					}
					""");
			else
				sb.AppendCSharp($$"""

					namespace {{ns.ToDisplayString()}}
					{
						partial class {{name}}
						{
							protected override void ConfigureNorseEntities(ModelBuilder builder)
							{
								base.ConfigureNorseEntities(builder);
								builder.ApplyNorseConfigurations();
							}
						}
					}
					""");
		}

		return sb.ToString();
	}
}
